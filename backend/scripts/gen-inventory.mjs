import fs from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadEnv } from "./lib/env.mjs";
import { withPool } from "./lib/pool.mjs";
import { listColumns } from "./lib/columns.mjs";

export const INVENTORY_TABLES = [
  "branches",
  "branch_products",
  "branch_stock_transfers",
  "branch_transfer_items",
  "branch_inventory_transactions",
  "orders",
  "users",
];

export const INVENTORY_PATH = new URL("../sql/inventory.md", import.meta.url);

// The rendered document is fully deterministic: identical schema in, identical
// bytes out. No timestamp is written, so re-running never dirties the file and
// `git diff` stays empty. `scripts/verify-phase1.mjs` compares this exact output
// against the committed file, which is what pins the format contract:
//
//   - one `### <table>` heading per table
//   - a `<n> columns.` count line
//   - a fenced block of `name  data_type` lines separated by TWO spaces
//
// Change the layout here, never in sql/inventory.md.
export async function renderInventory(pool, tables = INVENTORY_TABLES) {
  const { rows: meta } = await pool.query(
    "SELECT current_database() AS db, current_schema() AS schema, version() AS version",
  );

  const out = [];
  out.push("# Live column inventory (Phase 1)");
  out.push("");
  out.push("Authoritative reference for all branch-inventory SQL work. Generated by");
  out.push("`npm run gen:inventory` (i.e. `node scripts/gen-inventory.mjs`) from read-only");
  out.push("introspection of `information_schema.columns` against the live database");
  out.push("(not from `sql/schema.sql`).");
  out.push("");
  out.push("**Do not hand-edit this file.** Column names are copied verbatim from the");
  out.push("database, folded-lowercase spellings included. A later task that needs a");
  out.push("different spelling must ship a migration in `sql/migrations/` and then re-run");
  out.push("`npm run gen:inventory`. `node scripts/verify-phase1.mjs` fails if this file");
  out.push("drifts from the live schema.");
  out.push("");
  out.push(`- Database: \`${meta[0].db}\``);
  out.push(`- Schema: \`${meta[0].schema}\``);
  out.push(`- Server: ${meta[0].version.split(",")[0]}`);
  out.push("");
  out.push("## Naming conventions actually in the database");
  out.push("");
  out.push("| Group | Tables | Convention | Examples |");
  out.push("| --- | --- | --- | --- |");
  out.push(
    "| folded | branches, branch_products, branch_stock_transfers, branch_transfer_items, branch_inventory_transactions | lowercase, no separators; multiword names concatenated | `addressline1`, `stockquantity`, `sourcebranchid`, `previousstocksource` |",
  );
  out.push(
    "| snake_case | orders, users | lowercase with underscores | `order_number`, `created_at`, `payment_method`, `parent_id` |",
  );
  out.push("");
  out.push("Two tables mix both conventions, so check per column, never per table:");
  out.push("");
  out.push("- `branches` is folded throughout (`addressline1`, `createdat`, `countryid`) with one");
  out.push("  snake_case exception, `onboarding_completed`.");
  out.push("- `orders` is snake_case throughout (`order_number`, `payment_method`,");
  out.push("  `estimated_delivery_at`) with one folded exception, `branchid`.");
  out.push("");
  out.push("## Columns");
  out.push("");

  for (const table of tables) {
    const cols = await listColumns(pool, table);
    out.push(`### ${table}`);
    out.push("");
    out.push(`${cols.length} columns.`);
    out.push("");
    out.push("```");
    out.push(cols.map((c) => `${c.name}  ${c.dataType}`).join("\n"));
    out.push("```");
    out.push("");
  }

  return out.join("\n");
}

export async function writeInventory(pool, tables = INVENTORY_TABLES) {
  const text = await renderInventory(pool, tables);
  const target = fileURLToPath(INVENTORY_PATH);
  const before = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  fs.writeFileSync(target, text);
  return { path: target, changed: before !== text };
}

if (process.argv[1] && import.meta.url === pathToFileURL(fs.realpathSync(process.argv[1])).href) {
  await loadEnv();
  const { path, changed } = await withPool((pool) => writeInventory(pool));
  console.log(`${changed ? "wrote" : "unchanged"}  ${path}`);
}
